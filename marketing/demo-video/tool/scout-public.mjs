import { chromium } from "playwright";
const out = process.argv[2];
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH || process.env.HOME + "/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome" });
const p = await b.newPage({ viewport: { width: 1080, height: 1350 } });
await p.goto("https://nasihaforyou.org/", { waitUntil: "networkidle", timeout: 60000 });
await p.waitForTimeout(1500);
const sec = p.getByText("Upcoming Events", { exact: true }).first();
console.log("heading", await sec.count());
const car = p.locator('[aria-roledescription="carousel"]').first();
console.log("carousel", await car.count());
await car.scrollIntoViewIfNeeded();
await p.mouse.move(5, 5);
await p.waitForTimeout(800);
const bb = await car.boundingBox(); console.log("box", JSON.stringify(bb), "scrollY", await p.evaluate(() => scrollY));
console.log("slides", await car.locator(":scope > *").count());
console.log("controls", JSON.stringify(await p.$$eval('[aria-label]', els => els.map(e => e.getAttribute('aria-label')).filter(l => /slide|next|prev/i.test(l)).slice(0,12))));
await p.evaluate(() => scrollBy(0, -250));
await p.waitForTimeout(400);
await p.screenshot({ path: out + "/home_events.png" });
await p.waitForTimeout(3400);
await p.screenshot({ path: out + "/home_events2.png" });
const total = await p.evaluate(() => document.body.scrollHeight);
console.log("pageH", total);
await p.evaluate(() => scrollTo(0, 0)); await p.waitForTimeout(500);
await p.screenshot({ path: out + "/home_top.png" });
await b.close();
